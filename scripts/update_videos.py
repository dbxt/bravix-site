#!/usr/bin/env python3
"""Regenerate the video grids in public/index.html from the channel RSS feed."""
import html, re, sys, urllib.request
import xml.etree.ElementTree as ET
from datetime import datetime

CHANNEL_ID = "UCBNsYs5xe2jgjOkSLeDhbMg"
FEED = f"https://www.youtube.com/feeds/videos.xml?channel_id={CHANNEL_ID}"
INDEX = "public/index.html"
NS = {"a": "http://www.w3.org/2005/Atom", "y": "http://www.youtube.com/xml/schemas/2015",
      "m": "http://search.yahoo.com/mrss/"}

def fetch():
    with urllib.request.urlopen(FEED, timeout=30) as r:
        root = ET.fromstring(r.read())
    vids = []
    for e in root.findall("a:entry", NS):
        title = re.sub(r"\s*#\S*", "", e.findtext("a:title", "", NS)).strip() or "Untitled"
        stats = e.find("m:group/m:community/m:statistics", NS)
        vids.append({
            "id": e.findtext("y:videoId", "", NS), "title": title,
            "date": datetime.fromisoformat(e.findtext("a:published", "", NS)),
            "views": int(stats.get("views", 0)) if stats is not None else 0})
    return vids

def fmt(n):
    return f"{n/1000:.1f}K".replace(".0K", "K") if n >= 1000 else str(n)

def card(v):
    t = html.escape(v["title"])
    meta = f'{fmt(v["views"])} views · {v["date"]:%b %-d, %Y}'
    return (f'          <a class="card" href="https://www.youtube.com/watch?v={v["id"]}" target="_blank" rel="noopener">'
            f'<div class="thumb"><img src="https://i.ytimg.com/vi/{v["id"]}/hqdefault.jpg" alt="{t}" loading="lazy" />'
            f'<span class="play">▶</span></div><div class="body"><h3>{t}</h3><p>{meta}</p></div></a>')

def grid(vs):
    return '        <div class="grid">\n' + "\n".join(card(v) for v in vs) + "\n        </div>"

def main():
    import time
    vids = None
    for _ in range(4):
        try:
            vids = fetch()
            break
        except Exception as e:
            print("feed fetch failed:", e)
            time.sleep(5)
    if vids is None:
        print("feed unavailable; keeping existing videos")
        return
    if not vids:
        sys.exit("empty feed; leaving page unchanged")
    top = sorted(vids, key=lambda v: v["views"], reverse=True)[:4]
    ids = {v["id"] for v in top}
    latest = [v for v in sorted(vids, key=lambda v: v["date"], reverse=True) if v["id"] not in ids][:4]
    block = ('<!-- VIDEOS:START (generated by scripts/update_videos.py) -->\n'
             '        <h2>Top clips</h2>\n        <p class="sub">Most-watched from the channel. Click to watch on YouTube.</p>\n'
             + grid(top) +
             '\n        <h2 style="margin-top:3.5rem">Latest uploads</h2>\n        <p class="sub">Fresh off the timeline.</p>\n'
             + grid(latest) + '\n        <!-- VIDEOS:END -->')
    src = open(INDEX, encoding="utf8").read()
    new, n = re.subn(r"<!-- VIDEOS:START.*?<!-- VIDEOS:END -->", lambda m: block, src, flags=re.S)
    if n != 1:
        sys.exit("markers not found")
    if new != src:
        open(INDEX, "w", encoding="utf8").write(new)
        print("updated")
    else:
        print("no change")

main()
